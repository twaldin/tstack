class Setup:
    def __init__(self, dry_run: bool):
        self.dry_run = dry_run
        self.actions: list[str] = []
        self.day = dt.date.today().isoformat()

    def ours(self, path: Path) -> bool:
        """A symlink into the engine or instance, or a file carrying the setup marker."""
        if path.is_symlink():
            target = os.path.abspath(os.path.join(path.parent, os.readlink(path)))
            roots = [str(engine_home().resolve()), str(instance_home().resolve()), str(engine_home()), str(instance_home())]
            return any(target == r or target.startswith(r + os.sep) for r in roots)
        if path.is_file():
            with open(path, errors="replace") as handle:
                return MARK in handle.read(4096)
        return False

    def quarantine(self, path: Path, reason: str) -> None:
        rel = path.relative_to(HOME) if str(path).startswith(str(HOME) + os.sep) else Path(str(path).lstrip("/"))
        root = HOME / ".cleanup-quarantine" / self.day
        dest = root / rel
        n = 1
        while dest.exists() or dest.is_symlink():
            dest = root / f"{rel}.{n}"
            n += 1
        self.actions.append(f"quarantine {path} -> {dest} ({reason})")
        if self.dry_run:
            return
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.move(str(path), str(dest))
        with open(root / "MANIFEST.tsv", "a") as manifest:
            manifest.write(f"{iso()}\t{path}\t{dest}\t{reason}\n")

    def clear(self, path: Path, reason: str) -> None:
        """Make room at `path`: drop our own link or file, quarantine anything else."""
        if not (path.exists() or path.is_symlink()):
            return
        if self.ours(path):
            self.actions.append(f"remove {path} ({reason})")
            if not self.dry_run:
                path.unlink()
        else:
            self.quarantine(path, reason)

    def link(self, path: Path, target: Path) -> None:
        if path.is_symlink() and os.readlink(path) == str(target):
            return
        self.clear(path, f"replaced by a link to {target}")
        self.actions.append(f"link {path} -> {target}")
        if not self.dry_run:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.symlink_to(target)

    def write(self, path: Path, text: str) -> None:
        if path.is_file() and not path.is_symlink() and path.read_text(errors="replace") == text:
            return
        if path.exists() or path.is_symlink():
            if self.ours(path) and not path.is_symlink():
                self.actions.append(f"rewrite {path}")
            else:
                self.clear(path, "replaced by a generated file")
                self.actions.append(f"write {path}")
        else:
            self.actions.append(f"write {path}")
        if not self.dry_run:
            write_atomic(path, text)

    def real_dir(self, path: Path) -> None:
        if path.is_dir() and not path.is_symlink():
            return
        self.clear(path, "replaced by a tstack-managed directory")
        self.actions.append(f"mkdir {path}")
        if not self.dry_run:
            path.mkdir(parents=True, exist_ok=True)

    def links_dir(self, path: Path, wanted: dict[str, Path], keep: set[str] = frozenset()) -> None:
        """`path` becomes a real directory holding exactly `wanted` links (plus `keep` names, left alone)."""
        self.real_dir(path)
        existing = sorted(path.iterdir()) if path.is_dir() and not path.is_symlink() else []
        for entry in existing:
            if entry.name not in wanted and entry.name not in keep:
                self.clear(entry, "not a tstack entry")
        for name, target in sorted(wanted.items()):
            self.link(path / name, target)


def sources(m: str) -> list[Path]:
    """Engine, instance and machine roots, in that order."""
    return [engine_home(), instance_home(), instance_home() / "machines" / m]


def entries(kind: str, m: str, pattern: str = "*") -> dict[str, Path]:
    """Name -> target for every engine, instance and machine `kind` entry; a duplicate name is an error."""
    found: dict[str, Path] = {}
    for root in sources(m):
        folder = root / kind
        if not folder.is_dir():
            continue
        for item in sorted(folder.iterdir()):
            if item.name.startswith(".") or not fnmatch.fnmatch(item.name, pattern):
                continue
            if item.name in found:
                raise Die(f"{kind}/{item.name} exists in both {found[item.name].parent} and {folder}")
            found[item.name] = item
    return found


def agents_md(m: str) -> str:
    parts = [engine_home() / "global.md", instance_home() / "global.md", instance_home() / "machines" / m / "global.md"]
    present = [p for p in parts if p.exists()]
    if not present or present[0] != parts[0]:
        raise Die(f"missing {parts[0]}")
    header = (f"<!-- {MARK} for machine {m} from: " + ", ".join(str(p) for p in present)
              + ". Edit those files and rerun `tstack setup`. -->\n")
    return header + "".join(f"\n<!-- source: {p} -->\n\n{p.read_text().strip()}\n" for p in present)


def unit_path() -> str:
    """PATH for the timer jobs: fixed, so the units do not depend on who ran setup."""
    brew = "/opt/homebrew/bin:" if IS_MAC else ""
    return f"{HOME}/.local/bin:{HOME}/.bun/bin:{brew}/usr/local/bin:/usr/bin:/bin"


def unit_text(template: Path, m: str) -> str:
    text = template.read_text()
    for key, value in (("@TSTACK_HOME@", str(engine_home())), ("@TSTACK_INSTANCE@", str(instance_home())),
                       ("@HOME@", str(HOME)), ("@PATH@", unit_path()), ("@MACHINE@", m)):
        text = text.replace(key, value)
    return text


def install_timers(s: Setup, m: str) -> None:
    if IS_MAC:
        agents = HOME / "Library" / "LaunchAgents"
        for template in sorted((engine_home() / "launchd").glob("*.plist")):
            before = len(s.actions)
            s.write(agents / template.name, unit_text(template, m).replace("Installed by", f"{MARK}. Installed by"))
            if len(s.actions) > before and not s.dry_run:
                domain = f"gui/{os.getuid()}"
                run(["launchctl", "bootout", f"{domain}/{template.stem}"], check=False)
                run(["launchctl", "bootstrap", domain, str(agents / template.name)])
        return
    units = HOME / ".config" / "systemd" / "user"
    changed = False
    for template in sorted((engine_home() / "systemd").iterdir()):
        before = len(s.actions)
        s.write(units / template.name, unit_text(template, m).replace("# Installed by", f"# {MARK}. Installed by"))
        changed |= len(s.actions) > before
    timers = [t.name for t in sorted((engine_home() / "systemd").glob("*.timer"))]
    if s.dry_run:
        return
    if changed:
        run(["systemctl", "--user", "daemon-reload"])
    for timer in timers:
        if not (units / "timers.target.wants" / timer).exists():
            s.actions.append(f"enable {timer}")
            run(["systemctl", "--user", "enable", "--now", timer])


def managed_path(text: str) -> bool:
    """An absolute path inside the engine or the instance."""
    path = Path(os.path.expanduser(str(text)))
    if not path.is_absolute():
        return False
    roots = {engine_home(), instance_home(), engine_home().resolve(), instance_home().resolve()}
    return any(path == root or root in path.parents for root in roots)


def reconcile_config(s: Setup) -> None:
    """omp's config.yml must leave native discovery on: skills.enabled and skills.enablePiUser true, no
    customDirectories outside tstack, no `native` in disabledProviders. Only those lines change."""
    path = OMP / "config.yml"
    if not path.is_file():
        return
    text = path.read_text()
    new, changes = ompconfig.reconcile(text, managed_path)
    if changes:
        s.actions.append(f"reconcile {path}: {'; '.join(changes)}")
        s.write(path, new)


def plan(s: Setup, m: str, timers: bool) -> None:
    s.write(OMP / "AGENTS.md", agents_md(m))
    reconcile_config(s)
    s.links_dir(OMP / "skills", entries("skills", m))
    s.links_dir(OMP / "agents", entries("agents", m, "*.md"))
    s.links_dir(OMP / "extensions", entries("extensions", m, "*.ts"), keep=KEEP_EXTENSIONS)
    for folder in OWNED_DIRS:
        if folder.is_dir() and not folder.is_symlink():
            for entry in sorted(folder.iterdir()):
                s.clear(entry, "omp discovery path tstack keeps empty")
        elif folder.is_symlink() or folder.exists():
            s.clear(folder, "omp discovery path tstack keeps empty")
    for path in OWNED_ABSENT:
        if path.exists() or path.is_symlink():
            s.clear(path, "omp discovery path tstack keeps absent")
    for folder in BYPASS_COMMANDS:
        for index in sorted(folder.glob("*/index.*")) if folder.is_dir() else []:
            s.clear(index.parent, "command module omp loads whatever disabledProviders says")
    binaries = {}
    for folder in (engine_home() / "bin", instance_home() / "bin", instance_home() / "machines" / m / "bin"):
        if folder.is_dir():
            binaries.update({p.name: p for p in sorted(folder.iterdir()) if p.is_file() and os.access(p, os.X_OK)})
    local_bin = HOME / ".local" / "bin"
    if local_bin.is_dir():
        for entry in sorted(local_bin.iterdir()):
            if entry.is_symlink() and entry.name not in binaries and s.ours(entry):
                s.clear(entry, "tstack link to a removed command")
    for name, target in sorted(binaries.items()):
        s.link(local_bin / name, target)
    if timers or not IS_MAC:
        install_timers(s, m)


def setup(machine_name: str | None, dry_run: bool = False, timers: bool = False) -> list[str]:
    if machine_name:
        os.environ["TSTACK_MACHINE"] = machine_name
    m = machine()
    s = Setup(dry_run)
    plan(s, m, timers)
    if not dry_run:
        (HOME / ".local" / "state" / "tstack").mkdir(parents=True, exist_ok=True)
    prefix = "would " if dry_run else ""
    return [prefix + a for a in s.actions] or [f"tstack setup: {m} is current"]


