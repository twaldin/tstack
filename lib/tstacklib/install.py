def size_caps() -> list[tuple[str, int]]:
    path = engine_home() / "AGENTS.md"
    if not path.exists():
        return []
    text = path.read_text()
    section = re.search(r"^## Size caps\n(.*?)(?=^## |\Z)", text, re.M | re.S)
    if not section:
        return []
    return [(m.group(1), int(m.group(2))) for m in re.finditer(r"^- `([^`]+)`: (\d+) lines$", section.group(1), re.M)]


def tracked_files(root: Path) -> list[Path]:
    listing = run(["git", "-C", str(root), "ls-files"], check=False).stdout.splitlines()
    files = [root / name for name in listing] if listing else [p for p in root.rglob("*") if p.is_file() and ".git" not in p.parts]
    return [p for p in files if p.is_file() and "__pycache__" not in p.parts]


def personal_patterns() -> list[re.Pattern]:
    """Home paths, emails outside the reserved example domains, phone numbers, this host's login and hostname."""
    host = socket.gethostname()
    words = {w for w in (os.environ.get("USER", ""), HOME.name, host, host.split(".")[0]) if len(w) >= 3}
    patterns = [r"/Users/[A-Za-z0-9_.-]+", r"/home/[A-Za-z0-9_.-]+",
                r"[\w.+-]+@(?![\w.-]*\b(?:example\.(?:com|org|net)|invalid|test|example|localhost)\b)[\w-]+(?:\.[\w-]+)+",
                r"\+?1?[ (]?\d{3}[) .-]\d{3}[ .-]\d{4}\b"]
    patterns += [rf"\b{re.escape(w)}\b" for w in sorted(words)]
    return [re.compile(p, re.I) for p in patterns]


def own_slug() -> str | None:
    url = git(engine_home(), "remote", "get-url", "origin", check=False)
    match = re.search(r"github\.com[:/]([^/]+/[^/]+?)(?:\.git)?$", url)
    return match.group(1) if match else None


def personal_data() -> list[str]:
    slug = own_slug()
    patterns = personal_patterns()
    problems = []
    for path in tracked_files(engine_home()):
        try:
            text = path.read_text()
        except (UnicodeDecodeError, OSError):
            continue
        for number, line in enumerate(text.splitlines(), 1):
            scrubbed = line.replace(slug, "") if slug else line
            hit = next((p.search(scrubbed) for p in patterns if p.search(scrubbed)), None)
            if hit:
                problems.append(f"personal data: {path.relative_to(engine_home())}:{number}: {hit.group(0)!r}")
    return problems


def check(machine_name: str | None) -> list[str]:
    if machine_name:
        os.environ["TSTACK_MACHINE"] = machine_name
    m = machine()
    problems = []
    s = Setup(dry_run=True)
    try:
        plan(s, m, timers=False)
    except Die as error:
        problems.append(f"setup: {error}")
    problems += [f"setup not current: {a}" for a in s.actions]
    for link in sorted((HOME / ".local" / "bin").glob("*")):
        if link.is_symlink() and s.ours(link) and not link.exists():
            problems.append(f"dangling link {link}")
    for seat in all_seats():
        problems += seatlib.validate(seat)
    root = engine_home()
    for pattern, cap in size_caps():
        for path in sorted(root.glob(pattern)):
            lines = len(path.read_text().splitlines())
            if lines > cap:
                problems.append(f"size cap: {path.relative_to(root)} has {lines} lines, cap {cap}")
    try:
        problems += foreign_entries() + extension_roots()
    except ompconfig.ConfigError as error:
        problems.append(f"omp config: {OMP / 'config.yml'}: {error}")
    problems += personal_data()
    return problems


def omp_config() -> dict:
    path = OMP / "config.yml"
    return ompconfig.load(path.read_text()) if path.is_file() else {}


def disabled_providers() -> set[str]:
    """Global string entries of disabledProviders in omp's config.yml (path-scoped entries ignored)."""
    return {item for item in omp_config().get("disabledProviders") or [] if isinstance(item, str)}


def extension_roots() -> list[str]:
    """Explicit extension paths (config.yml and settings.json `extensions`) outside tstack and easl."""
    paths = list(omp_config().get("extensions") or [])
    settings = OMP / "settings.json"
    if settings.is_file():
        try:
            paths += json.loads(settings.read_text()).get("extensions") or []
        except (ValueError, AttributeError):
            return [f"omp settings: {settings} is not a JSON object"]
    easl_roots = [Path("/Applications/easl.app"), HOME / ".local" / "share" / "easl", OMP / "extensions"]
    problems = []
    for item in paths:
        path = Path(os.path.expanduser(str(item)))
        inside = path.is_absolute() and (managed_path(str(path)) or any(r == path or r in path.parents for r in easl_roots))
        if not inside:
            problems.append(f"omp config: extension path {item} is outside tstack and easl")
    return problems


def foreign_entries() -> list[str]:
    """Entries in other harnesses' roots that omp loads because their provider is enabled."""
    disabled = disabled_providers()
    problems = []
    for provider, paths in FOREIGN.items():
        if provider in disabled:
            continue
        for rel in paths:
            path = HOME / rel
            if path.is_dir() and any(path.iterdir()) or path.is_file():
                problems.append(f"foreign: omp loads {path} (provider {provider}; add it to disabledProviders or clear it)")
    return problems


