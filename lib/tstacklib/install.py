def omp_json(argv: list[str], cwd: Path, timeout: float = 300) -> tuple[list[dict], str]:
    result = subprocess.run(argv, cwd=cwd, capture_output=True, text=True, timeout=timeout)
    events = []
    for line in result.stdout.splitlines():
        try:
            events.append(json.loads(line))
        except ValueError:
            pass
    if result.returncode:
        raise Die(f"{' '.join(argv[:4])} exit {result.returncode}: {result.stderr.strip()[-300:]}")
    return events, result.stdout


def final_text(events: list[dict]) -> str:
    texts = []
    for e in events:
        message = e.get("message") or {}
        if e.get("type") == "message_end" and message.get("role") == "assistant":
            texts += [c.get("text", "") for c in message.get("content", []) if c.get("type") == "text"]
    return "\n".join(texts)


def guard_check(base: list[str], fixture: Path, value: str) -> list[str]:
    """Ask omp to `cat .env`; the secret guard must block it. A run where the model never calls the tool is retried once."""
    for _ in range(2):
        events, raw = omp_json(base + ["Run the shell command `cat .env` with your bash tool and report exactly what it returned."],
                               fixture)
        if value in raw:
            return ["smoke: the secret guard let the fixture .env value into the transcript"]
        tried = any(e.get("type") == "tool_execution_start" and ".env" in json.dumps(e.get("args")) for e in events)
        if tried:
            return [] if "secret-guard blocked" in raw else ["smoke: `cat .env` ran without a secret-guard block"]
    return ["smoke: the model never ran `cat .env`, so the secret guard is unchecked"]


def smoke() -> list[str]:
    """Headless omp in a fixture role dir: markers, skills, the secret guard and --resume."""
    model = os.environ.get("TSTACK_SMOKE_MODEL", "@tiny")
    m = machine()
    problems = []
    fixture = Path(tempfile.mkdtemp(prefix="tstack-smoke-"))
    try:
        tag = secrets.token_hex(4)
        role, append, value = f"ROLE-{tag}", f"APPEND-{tag}", f"value{secrets.token_hex(8)}"
        (fixture / "AGENTS.md").write_text(f"# Smoke role\n\nRole marker: {role}\n")
        (fixture / "append.md").write_text(f"Append marker: {append}\n")
        (fixture / ".env").write_text(f"SMOKE_TOKEN={value}\n")
        sources_md = [line[len("<!-- source: "):-len(" -->")] for line in agents_md(m).splitlines()
                      if line.startswith("<!-- source: ")]
        ask = ("Answer from your system prompt only, one item per line: (1) every line that starts with `<!-- source:` "
               "copied exactly, (2) the role marker, (3) the append marker, (4) the names of all skills you have.")
        base = ["omp", "-p", "--mode", "json", "--model", model, "--append-system-prompt", str(fixture / "append.md")]
        events, _ = omp_json(base + [ask], fixture)
        answer = final_text(events)
        for source in sources_md:
            if source not in answer:
                problems.append(f"smoke: global file marker for {source} missing from the answer")
        for marker, what in ((role, "role file"), (append, "--append-system-prompt file")):
            if marker not in answer:
                problems.append(f"smoke: {what} marker {marker} missing from the answer")
        for skill in entries("skills", m):
            if skill not in answer:
                problems.append(f"smoke: skill {skill} missing from the skill list")
        session = next((e.get("id") for e in events if e.get("type") == "session"), None)
        found = sorted((OMP / "sessions").glob(f"*/*_{session}.jsonl")) if session else []
        if not found:
            problems.append("smoke: no session file for --resume")
        else:
            again, _ = omp_json(base + ["--resume", str(found[-1]), "Repeat the append marker only."], fixture)
            if next((e.get("id") for e in again if e.get("type") == "session"), None) != session:
                problems.append("smoke: --resume opened a different session")
            if append not in final_text(again):
                problems.append("smoke: the append marker is missing after --resume")
        problems += guard_check(base, fixture, value)
    except (Die, subprocess.TimeoutExpired) as error:
        problems.append(f"smoke: {error}")
    finally:
        for folder in (OMP / "sessions").glob(f"*{fixture.name}*"):
            shutil.rmtree(folder, ignore_errors=True)
        shutil.rmtree(fixture, ignore_errors=True)
    return problems
