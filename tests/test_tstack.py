class Setup(Sandbox):
    def setUp(self):
        super().setUp()
        self.engine, self.instance = self.root / "engine", self.home / "agents"
        files = {"global.md": "# Engine rules\n", "agents/opus.md": "opus\n", "bin/lane": (CODE / "bin" / "lane").read_text(),
                 "pstack/skills/poteto-mode/SKILL.md": "pm\n", "pstack/skills/poteto-mode/scripts/package.json": "{}\n",
                 "pstack/skills/principle-x/SKILL.md": "x\n", "pstack/agents/poteto-agent.md": "pa\n",
                 "systemd/tstack-update.unit": "# generated by tstack setup\nrun @ENGINE@ @INSTANCE@ @MACHINE@\n",
                 "bin/tstack": (CODE / "bin" / "tstack").read_text()}
        self.clone(self.root / "engine.git", self.engine, files)
        shutil.rmtree(self.instance)
        self.clone(self.root / "agents.git", self.instance, {
            "global.md": "# Instance rules\n", "skills/writing/SKILL.md": "w\n", "bin/text": "#!/bin/sh\n",
            "machines/box/global.md": "# Box\n", "machines/box/skills/mac-gui/SKILL.md": "m\n"})
