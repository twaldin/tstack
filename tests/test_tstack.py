    def test_update_pulls_both_reports_what_moved_and_reruns_setup(self):
        old = git(self.instance, "rev-parse", "--short", "HEAD")
        seed = self.root / "seed-agents"
        (seed / "skills" / "new").mkdir()
        (seed / "skills" / "new" / "SKILL.md").write_text("n\n")
        git(seed, "add", "-A")
        git(seed, "commit", "--quiet", "-m", "new skill")
        git(seed, "push", "--quiet", str(self.root / "agents.git"), "main")
        (self.engine / "global.md").write_text("# Local edit\n")
        git(self.engine, "commit", "--quiet", "-am", "local")
        git(self.root / "seed-engine", "commit", "--quiet", "--allow-empty", "-m", "upstream")
        git(self.root / "seed-engine", "push", "--quiet", str(self.root / "engine.git"), "main")
        engine = git(self.engine, "rev-parse", "--short", "HEAD")
        result = self.cli("tstack", "update", check=False)
        new = git(self.instance, "rev-parse", "--short", "HEAD")
        self.assertEqual(result.returncode, 1)
        self.assertTrue(result.stdout.startswith(f"engine: pull failed at {engine}: "))
        self.assertIn(f"\ninstance: {old}..{new}\n", result.stdout)
        self.assertEqual(os.readlink(self.home / ".omp/agent/skills/new"), str(self.instance / "skills" / "new"))



