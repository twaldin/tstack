import json
import os
import shutil
import sys
import unittest
from pathlib import Path

from support import CODE, Sandbox, git

UNITS = ("launchd", "Library/LaunchAgents") if sys.platform == "darwin" else ("systemd", ".config/systemd/user")


class Setup(Sandbox):
    def setUp(self):
        super().setUp()
        self.engine, self.instance = self.root / "engine", self.home / "agents"
        files = {"global.md": "# Engine rules\n", "agents/opus.md": "opus\n", "bin/lane": (CODE / "bin" / "lane").read_text(),
                 "pstack/skills/poteto-mode/SKILL.md": "pm\n", "pstack/skills/poteto-mode/scripts/package.json": "{}\n",
                 "pstack/skills/principle-x/SKILL.md": "x\n", "pstack/agents/poteto-agent.md": "pa\n",
                 f"{UNITS[0]}/tstack-update.unit": "unit\n", "bin/tstack": (CODE / "bin" / "tstack").read_text()}
        self.clone(self.root / "engine.git", self.engine, files)
        shutil.rmtree(self.instance)
        self.clone(self.root / "agents.git", self.instance, {
            "global.md": "# Instance rules\n", "skills/writing/SKILL.md": "w\n", "bin/text": "#!/bin/sh\n",
            "machines/box/global.md": "# Box\n", "machines/box/skills/mac-gui/SKILL.md": "m\n"})
        (self.seat / "state").mkdir(parents=True)
        self.env.update(TSTACK_HOME=str(self.engine), TSTACK_INSTANCE=str(self.instance))

    def links(self, folder: str) -> dict:
        root = self.home / folder
        return {p.name: os.readlink(p) for p in sorted(root.iterdir()) if p.is_symlink()}

    def test_setup_links_everything_and_writes_agents_md(self):
        self.cli("tstack", "setup")
        pstack, box = self.engine / "pstack", self.instance / "machines" / "box"
        self.assertEqual(self.links(".omp/agent/skills"), {
            "mac-gui": str(box / "skills" / "mac-gui"), "poteto-mode": str(pstack / "skills" / "poteto-mode"),
            "principle-x": str(pstack / "skills" / "principle-x"), "writing": str(self.instance / "skills" / "writing")})
        self.assertEqual(self.links(".omp/agent/agents"), {
            "opus.md": str(self.engine / "agents" / "opus.md"), "poteto-agent.md": str(pstack / "agents" / "poteto-agent.md")})
        self.assertEqual(self.links(".local/bin"), {
            "lane": str(self.engine / "bin" / "lane"), "text": str(self.instance / "bin" / "text"),
            "tstack": str(self.engine / "bin" / "tstack")})
        self.assertEqual(self.links(UNITS[1]), {"tstack-update.unit": str(self.engine / UNITS[0] / "tstack-update.unit")})
        sources = ", ".join(str(p) for p in (self.engine / "global.md", self.instance / "global.md", box / "global.md"))
        self.assertEqual((self.home / ".omp/agent/AGENTS.md").read_text(),
                         f"<!-- generated by tstack setup from {sources}. Edit those, then rerun `tstack setup`. -->\n"
                         "\n# Engine rules\n\n# Instance rules\n\n# Box\n")
        self.assertEqual((self.stubs / "bun.log").read_text(),
                         f"{(pstack / 'skills/poteto-mode/scripts').resolve()} install --frozen-lockfile\n")
        self.assertEqual(self.cli("tstack", "setup").stdout, "tstack setup: box is current\n")

    def test_setup_replaces_only_its_own_links(self):
        skills, bins = self.home / ".omp/agent/skills", self.home / ".local/bin"
        (skills / "writing").mkdir(parents=True)
        bins.mkdir(parents=True)
        (bins / "secret-check").symlink_to(self.engine / "bin" / "secret-check")
        (bins / "other").symlink_to("/usr/bin/true")
        out = self.cli("tstack", "setup").stdout.splitlines()
        self.assertIn(f"left {skills / 'writing'}: not a tstack link (wanted -> {self.instance / 'skills' / 'writing'})", out)
        self.assertIn(f"removed {bins / 'secret-check'}", out)
        self.assertEqual(((skills / "writing").is_dir(), os.readlink(bins / "other")), (True, "/usr/bin/true"))
        self.assertFalse((bins / "secret-check").is_symlink())

    def test_setup_without_pstack_says_so_and_links_the_rest(self):
        shutil.rmtree(self.engine / "pstack")
        out = self.cli("tstack", "setup").stdout.splitlines()
        self.assertEqual(out[:2], [f"skip {self.engine / 'pstack' / 'skills'}: missing",
                                   f"skip {self.engine / 'pstack' / 'agents'}: missing"])
        self.assertIn(f"skip bun install: no {self.engine / 'pstack/skills/poteto-mode/scripts/package.json'}", out)
        self.assertEqual(self.links(".omp/agent/agents"), {"opus.md": str(self.engine / "agents" / "opus.md")})

    def test_update_pulls_both_reports_what_moved_and_reruns_setup(self):
        old = git(self.instance, "rev-parse", "--short", "HEAD")
        seed = self.root / "seed-agents"
        (seed / "skills" / "new").mkdir()
        (seed / "skills" / "new" / "SKILL.md").write_text("n\n")
        git(seed, "add", "-A")
        git(seed, "commit", "--quiet", "-m", "new skill")
        git(seed, "push", "--quiet", str(self.root / "agents.git"), "main")
        (self.engine / "global.md").write_text("# Local edit\n")
        git(self.engine, "commit", "--quiet", "-am", "local")
        git(self.root / "seed-engine", "commit", "--quiet", "--allow-empty", "-m", "upstream")
        git(self.root / "seed-engine", "push", "--quiet", str(self.root / "engine.git"), "main")
        engine = git(self.engine, "rev-parse", "--short", "HEAD")
        result = self.cli("tstack", "update", check=False)
        new = git(self.instance, "rev-parse", "--short", "HEAD")
        self.assertEqual(result.returncode, 1)
        self.assertTrue(result.stdout.startswith(f"engine: pull failed at {engine}: "))
        self.assertIn(f"\ninstance: {old}..{new}\n", result.stdout)
        self.assertEqual(os.readlink(self.home / ".omp/agent/skills/new"), str(self.instance / "skills" / "new"))

    def test_board_writes_one_note_per_seat(self):
        (self.seat / "state" / "board.json").write_text(json.dumps({"host": "box", "board": "brd_a", "tile": "obj_t"}))
        (self.stubs / "asks.json").write_text(json.dumps({"objects": [{"id": "obj_q", "props": {"question": "Ship?"}}]}))
        demo = self.instance / "projects" / "demo" / "state"
        (demo / "orch").mkdir(parents=True)
        (demo / "orch" / "status.md").write_text("2 units in flight\n")
        self.assertEqual(self.cli("tstack", "board").stdout, "seat:assistant\nseat:projects/demo\n")
        upserts = [c for c in self.log("easl.log") if c[0] == "object.upsert"]
        self.assertEqual([c[:5] for c in upserts], [["object.upsert", "--board", "brd_a", "--key", "seat:assistant"],
                                                    ["object.upsert", "--board", "brd_a", "--key", "seat:projects/demo"]])
        assistant, project = (json.loads(c[-1])["props"]["markdown"] for c in upserts)
        self.assertIn("### Open questions\n\n- Ship? (`obj_q`)\n", assistant)
        self.assertIn("### Lanes\n\n```\nnone\n```\n\n### orch\n\n2 units in flight\n", project)


if __name__ == "__main__":
    unittest.main()
