    def test_update_pulls_engine_safely_syncs_dirty_instance_and_reruns_setup(self):
        old = git(self.instance, "rev-parse", "--short", "HEAD")
        seed = self.root / "seed-agents"
        (seed / "skills" / "new").mkdir()
        (seed / "skills" / "new" / "SKILL.md").write_text("n\n")
        (seed / "global.md").write_text("# Upstream rules\n")
        (seed / "orders.md").write_text("upstream orders\n")
        (seed / "assistant/state/status.md").write_text("upstream state\n")
        (self.instance / "global.md").write_text("# Local rules\n")
        (self.instance / "orders.md").write_text("staged orders\n")
        (self.seat / "state/status.md").write_text("staged state\n")
        git(self.instance, "add", "orders.md", "assistant/state/status.md")
        (self.seat / "state/status.md").write_text("live writer\n")
        git(seed, "add", "-A")
        git(seed, "commit", "--quiet", "-m", "new skill")
        git(seed, "push", "--quiet", str(self.root / "agents.git"), "main")
        (self.engine / "global.md").write_text("# Local edit\n")
        git(self.engine, "commit", "--quiet", "-am", "local")
        git(self.root / "seed-engine", "commit", "--quiet", "--allow-empty", "-m", "upstream")
        git(self.root / "seed-engine", "push", "--quiet", str(self.root / "engine.git"), "main")
        engine = git(self.engine, "rev-parse", "--short", "HEAD")
        result = self.cli("tstack", "update", check=False)
        new = git(self.instance, "rev-parse", "--short", "HEAD")
        self.assertEqual(result.returncode, 1)
        self.assertTrue(result.stdout.startswith(f"engine: pull failed at {engine}: "))
        self.assertIn(f"\ninstance: {old}..{new}\n", result.stdout)
        self.assertEqual(os.readlink(self.home / ".omp/agent/skills/new"), str(self.instance / "skills" / "new"))
        self.assertEqual((self.instance / "global.md").read_text(), "# Local rules\n")
        self.assertEqual((self.instance / "orders.md").read_text(), "staged orders\n")
        self.assertEqual((self.seat / "state/status.md").read_text(), "live writer\n")
        self.assertEqual(git(self.instance, "show", ":orders.md"), "staged orders")
        self.assertEqual(git(self.instance, "show", ":assistant/state/status.md"), "staged state")
        self.assertIn("skipped orders.md: staged edit", result.stdout)
        self.assertIn("skipped assistant/state/status.md: staged edit", result.stdout)
        self.assertIn("synced skills/new/SKILL.md", result.stdout)

